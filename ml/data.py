"""
ExoVet Data Ingestion & Leakage Prevention Module
Handles reading raw NASA Kepler KOI cumulative catalog, audits leakage,
and prepares clean datasets for training and scoring.
"""

import os
import pandas as pd
import numpy as np
from typing import Tuple, Dict, Any

# Primary physical and observational features (strictly no post-vetting indicators)
FEATURE_COLUMNS = [
    'koi_period',     # Orbital period [days]
    'koi_duration',   # Transit duration [hrs]
    'koi_depth',      # Transit depth [ppm]
    'koi_prad',       # Planet radius [Earth radii]
    'koi_model_snr',  # Transit signal-to-noise ratio
    'koi_impact',     # Impact parameter
    'koi_teq',        # Equilibrium temperature [K]
    'koi_insol',      # Insolation flux [Earth flux]
    'koi_steff',      # Stellar effective temperature [K]
    'koi_slogg',      # Stellar surface gravity [log10(cm/s^2)]
    'koi_srad',       # Stellar radius [Solar radii]
    'koi_kepmag'      # Kepler-band magnitude
]
BASE_FEATURES = FEATURE_COLUMNS

# Leakage columns that MUST NEVER be fed into the models
LEAKAGE_COLUMNS = [
    'koi_score',        # Robovetter disposition score (direct probability from pipeline)
    'koi_pdisposition', # Robovetter pipeline disposition
    'koi_fpflag_nt',    # Not-transit flag (human/pipeline vetted)
    'koi_fpflag_ss',    # Stellar eclipse flag (human/pipeline vetted)
    'koi_fpflag_co',    # Centroid offset flag (human/pipeline vetted)
    'koi_fpflag_ec',    # Ephemeris match contamination flag
    'koi_comment',      # Notes from vetting teams
    'koi_disp_prov',    # Disposition provenance
    'koi_vet_stat',     # Vetting status
    'koi_vet_date'      # Vetting date
]

METADATA_COLUMNS = ['kepid', 'kepoi_name', 'kepler_name', 'ra', 'dec']


def load_raw_data(filepath: str = "data/raw/kepler_cumulative.csv") -> pd.DataFrame:
    """Load raw Kepler cumulative data."""
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Raw data file not found at {filepath}")
    return pd.read_csv(filepath)


def audit_leakage(df: pd.DataFrame) -> Dict[str, Any]:
    """
    Perform audit of leakage columns present in raw data.
    Documents why each column is dropped.
    """
    present_leakage = [col for col in LEAKAGE_COLUMNS if col in df.columns]
    audit_report = {
        "identified_leakage_columns": present_leakage,
        "reasoning": {
            "koi_score": "Generated by Kepler Robovetter pipeline as a vetting probability. Using it leaks the final decision.",
            "koi_pdisposition": "Direct pipeline classification assigned during vetting.",
            "koi_fpflag_nt": "Flag explicitly indicating non-transit events identified during manual/pipeline vetting.",
            "koi_fpflag_ss": "Flag indicating stellar/secondary eclipse identified during vetting.",
            "koi_fpflag_co": "Flag indicating centroid offset (background star) identified during vetting.",
            "koi_fpflag_ec": "Flag indicating ephemeris contamination from nearby variable star.",
            "koi_vet_*": "Metadata generated after vetting has occurred."
        },
        "action": "All leakage columns are strictly excluded from the training and inference feature matrices."
    }
    return audit_report


def prepare_datasets(filepath: str = "data/raw/kepler_cumulative.csv") -> Tuple[pd.DataFrame, pd.DataFrame, Dict[str, Any]]:
    """
    Load data, clean, separate labeled training data (CONFIRMED vs FALSE POSITIVE)
    and unlabelled candidate data (CANDIDATE).
    """
    df = load_raw_data(filepath)
    leakage_report = audit_leakage(df)
    
    # Filter only CONFIRMED and FALSE POSITIVE for model training
    labeled_mask = df['koi_disposition'].isin(['CONFIRMED', 'FALSE POSITIVE'])
    labeled_df = df[labeled_mask].copy()
    
    # Map target: CONFIRMED = 1, FALSE POSITIVE = 0
    labeled_df['target'] = (labeled_df['koi_disposition'] == 'CONFIRMED').astype(int)
    
    # Candidate dataset for active scoring & exploration
    candidate_df = df[df['koi_disposition'] == 'CANDIDATE'].copy()
    
    # Save processed subsets
    os.makedirs("data/processed", exist_ok=True)
    labeled_df.to_csv("data/processed/labeled_koi.csv", index=False)
    candidate_df.to_csv("data/processed/candidates_koi.csv", index=False)
    
    return labeled_df, candidate_df, leakage_report


if __name__ == "__main__":
    print("Running ExoVet Data Ingestion & Leakage Audit...")
    labeled, candidates, report = prepare_datasets()
    print(f"Labeled dataset shape: {labeled.shape} (Confirmed: {(labeled['target']==1).sum()}, False Positive: {(labeled['target']==0).sum()})")
    print(f"Unlabelled Candidate dataset shape: {candidates.shape}")
    print(f"Audit report: {report['action']}")
